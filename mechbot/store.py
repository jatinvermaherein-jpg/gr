class Store:
    def __init__(self, sqlite_path=None, pool=None, supports_announcements=True, supports_conversations=True):
        self.pool = pool
        self.supports_announcements = bool(supports_announcements)
        self.supports_conversations = bool(supports_conversations)
        self.lock = asyncio.Lock()
        self.db = None
        if pool is None:
            path = Path(sqlite_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            self.db = sqlite3.connect(path, isolation_level=None)
            self.db.row_factory = sqlite3.Row
            self.db.executescript(SQLITE_DDL)

    @classmethod
    async def postgres(cls, dsn, auto_migrate=False, ssl_required=True):
        import asyncpg
        # Disable prepared statement caching for Supabase transaction poolers.
        pool = await asyncpg.create_pool(dsn, min_size=1, max_size=4, statement_cache_size=0, ssl='require' if ssl_required else None, command_timeout=20)
        supports_announcements=False
        supports_conversations=False
        try:
            async with pool.acquire() as conn:
                if auto_migrate:
                    await conn.execute(PG_DDL)
                # Fail fast if the existing private runtime schema is not installed.
                for table in ('profiles', 'reminders', 'notes', 'worker_campaign', 'worker_reminders', 'payout_alerts'):
                    await conn.fetchval('SELECT 1 FROM mech_bot_app.'+table+' LIMIT 1')
                supports_announcements=bool(await conn.fetchval("SELECT to_regclass('mech_bot_app.announcements') IS NOT NULL"))
                supports_conversations=bool(await conn.fetchval("SELECT to_regclass('mech_bot_app.conversation_turns') IS NOT NULL"))
        except Exception:
            await pool.close()
            raise
        return cls(pool=pool,supports_announcements=supports_announcements,supports_conversations=supports_conversations)

    async def close(self):
        if self.pool:
            await self.pool.close()
        if self.db:
            self.db.close()

    def _query(self, sql):
        if self.pool:
            for name in ('conversation_turns','worker_campaign','worker_reminders','payout_alerts','announcements','profiles','reminders','notes'):
                sql = re.sub(r'(?<![\w.])'+name+r'\b', 'mech_bot_app.'+name, sql)
            return sql
        return re.sub(r'\$\d+', '?', sql)

    async def fetch(self, sql, *args):
        sql = self._query(sql)
        if self.pool:
            async with self.pool.acquire() as conn:
                return [dict(x) for x in await conn.fetch(sql, *args)]
        async with self.lock:
            return [dict(x) for x in self.db.execute(sql, args).fetchall()]

    async def execute(self, sql, *args):
        sql = self._query(sql)
        if self.pool:
            async with self.pool.acquire() as conn:
                return await conn.execute(sql, *args)
        async with self.lock:
            cur = self.db.execute(sql, args)
            return cur.rowcount

    async def upsert_announcements(self, records):
        if not self.supports_announcements:raise RuntimeError('The private announcement table has not been migrated.')
        columns=('channel_id','message_id','guild_id','guild_name','channel_name','content','message_url','posted_at','edited_at','fetched_at')
        updates=','.join(f'{name}=excluded.{name}' for name in columns[2:])
        for offset in range(0,len(records),50):
            batch=records[offset:offset+50]
            if not batch:continue
            args=[];values=[]
            for record in batch:
                cells=[]
                for name in columns:
                    args.append(record.get(name))
                    cells.append(f'${len(args)}')
                values.append('('+','.join(cells)+')')
            sql=('INSERT INTO announcements('+','.join(columns)+') VALUES '+','.join(values)
                 +' ON CONFLICT(channel_id,message_id) DO UPDATE SET '+updates)
            await self.execute(sql,*args)

    async def announcement_cursor(self, channel_id):
        if not self.supports_announcements:return None
        rows=await self.fetch('''SELECT message_id FROM announcements WHERE channel_id=$1
            ORDER BY posted_at DESC,CAST(message_id AS BIGINT) DESC LIMIT 1''',str(channel_id))
        return int(rows[0]['message_id']) if rows else None

    async def recent_announcements(self, since, limit=1000):
        if not self.supports_announcements:return []
        return await self.fetch('''SELECT channel_id,message_id,guild_id,guild_name,channel_name,content,
            message_url,posted_at,edited_at,fetched_at FROM announcements
            WHERE posted_at >= $1 ORDER BY posted_at DESC,CAST(message_id AS BIGINT) DESC LIMIT $2''',
            int(since),max(1,min(int(limit),2000)))

    async def conversation_history(self, user_id, guild_id, channel_id, now=None):
        """Return at most five unexpired turns for this user in this exact channel/DM."""
        if not self.supports_conversations:return []
        now=int(time.time()) if now is None else int(now)
        await self.delete_expired_conversation_turns(now)
        rows=await self.fetch('''SELECT user_content,assistant_content FROM conversation_turns
            WHERE user_id=$1 AND guild_id=$2 AND channel_id=$3 AND expires_at>$4
            ORDER BY created_at DESC,id DESC LIMIT $5''',
            str(user_id),str(guild_id or ''),str(channel_id),now,CONVERSATION_TURN_LIMIT)
        messages=[]
        for row in reversed(rows):
            messages.append({'role':'user','content':row['user_content']})
            messages.append({'role':'assistant','content':row['assistant_content']})
        return messages

    async def add_conversation_turn(self, user_id, guild_id, channel_id, user_content, assistant_content, created_at=None):
        """Persist one bot-directed exchange with a hard five-hour expiry and five-turn cap."""
        if not self.supports_conversations:return False
        created=int(time.time()) if created_at is None else int(created_at)
        expires=created+CONVERSATION_TTL_SECONDS
        if expires<=int(time.time()):return False
        user_content=str(user_content or '').strip()[:CONVERSATION_TEXT_LIMIT]
        assistant_content=str(assistant_content or '').strip()[:CONVERSATION_TEXT_LIMIT]
        if not user_content or not assistant_content:return False
        scope=(str(user_id),str(guild_id or ''),str(channel_id))
        await self.fetch('''INSERT INTO conversation_turns
            (user_id,guild_id,channel_id,user_content,assistant_content,created_at,expires_at)
            VALUES($1,$2,$3,$4,$5,$6,$7) RETURNING id''',*scope,user_content,assistant_content,created,expires)
        now=int(time.time())
        await self.execute('''DELETE FROM conversation_turns WHERE user_id=$1 AND guild_id=$2 AND channel_id=$3
            AND id NOT IN (SELECT id FROM conversation_turns WHERE user_id=$4 AND guild_id=$5 AND channel_id=$6
                AND expires_at>$7 ORDER BY created_at DESC,id DESC LIMIT $8)''',
            *scope,*scope,now,CONVERSATION_TURN_LIMIT)
        await self.delete_expired_conversation_turns()
        return True

    async def delete_expired_conversation_turns(self, now=None):
        """Physically purge expired turns. Reads always filter by expiry before returning context."""
        if not self.supports_conversations:return
        now=int(time.time()) if now is None else int(now)
        await self.execute('DELETE FROM conversation_turns WHERE expires_at<=$1',now)

    async def set_timezone(self, user_id, zone):
        await self.execute('INSERT INTO profiles(user_id,timezone) VALUES($1,$2) ON CONFLICT(user_id) DO UPDATE SET timezone=excluded.timezone', str(user_id), zone)

    async def get_timezone(self, user_id):
        rows = await self.fetch('SELECT timezone FROM profiles WHERE user_id=$1', str(user_id))
        return rows[0]['timezone'] if rows else 'UTC'

    async def create_reminder(self, user_id, content, spec, zone):
        due, kind, interval, hour, minute = spec
        rows = await self.fetch('INSERT INTO reminders(user_id,content,due_at,zone,kind,interval_seconds,hour,minute,created_at) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9) RETURNING id', str(user_id), content, due, zone, kind, interval, hour, minute, int(time.time()))
        return rows[0]['id']

    async def list_reminders(self, user_id):
        return await self.fetch("SELECT id,content,due_at,zone,kind,status,last_error FROM reminders WHERE user_id=$1 AND status IN ('pending','delivering','failed') ORDER BY due_at LIMIT 25", str(user_id))

    async def cancel_reminder(self, user_id, reminder_id):
        # Owner scope is mandatory. In-flight delivery may already have been sent.
        rows = await self.fetch("UPDATE reminders SET status='cancelled',lease_token=NULL WHERE id=$1 AND user_id=$2 AND status IN ('pending','delivering','failed') RETURNING id", reminder_id, str(user_id))
        return bool(rows)

    async def add_note(self, user_id, content):
        rows = await self.fetch('INSERT INTO notes(user_id,content,created_at) VALUES($1,$2,$3) RETURNING id', str(user_id), content, int(time.time()))
        return rows[0]['id']

    async def list_notes(self, user_id):
        return await self.fetch('SELECT id,content FROM notes WHERE user_id=$1 ORDER BY id DESC LIMIT 25', str(user_id))

    async def delete_note(self, user_id, note_id):
        rows = await self.fetch('DELETE FROM notes WHERE id=$1 AND user_id=$2 RETURNING id', note_id, str(user_id))
        return bool(rows)

    async def claim(self, now, limit=5):
        token = uuid.uuid4().hex
        if self.pool:
            # Atomic multi-worker claim; an expired lease allows recovery after a crash.
            query = '''WITH due AS (
              SELECT id FROM mech_bot_app.reminders
              WHERE (status='pending' AND due_at <= $1) OR (status='delivering' AND lease_until <= $1)
              ORDER BY due_at FOR UPDATE SKIP LOCKED LIMIT $2
            ) UPDATE mech_bot_app.reminders r SET status='delivering', lease_until=$3, lease_token=$4
              FROM due WHERE r.id=due.id RETURNING r.*'''
            async with self.pool.acquire() as conn:
                return [dict(r) for r in await conn.fetch(query, now, limit, now+120, token)]
        async with self.lock:
            self.db.execute('BEGIN IMMEDIATE')
            try:
                ids = [r[0] for r in self.db.execute("SELECT id FROM reminders WHERE (status='pending' AND due_at <= ?) OR (status='delivering' AND lease_until <= ?) ORDER BY due_at LIMIT ?",(now,now,limit))]
                result = []
                for rid in ids:
                    self.db.execute("UPDATE reminders SET status='delivering',lease_until=?,lease_token=? WHERE id=?", (now+120,token,rid))
                    result.append(dict(self.db.execute('SELECT * FROM reminders WHERE id=?',(rid,)).fetchone()))
                self.db.commit()
                return result
            except Exception:
                self.db.rollback()
                raise

    async def complete(self, row, next_due):
        if next_due is None:
            await self.execute("UPDATE reminders SET status='completed',lease_until=NULL,lease_token=NULL,last_error=NULL WHERE id=$1 AND status='delivering' AND lease_token=$2", row['id'], row['lease_token'])
        else:
            await self.execute("UPDATE reminders SET status='pending',due_at=$1,lease_until=NULL,lease_token=NULL,last_error=NULL WHERE id=$2 AND status='delivering' AND lease_token=$3", next_due, row['id'], row['lease_token'])

    async def fail(self, row, message='DM delivery failed; enable DMs, then create a new reminder.'):
        await self.execute("UPDATE reminders SET status='failed',lease_until=NULL,lease_token=NULL,last_error=$1 WHERE id=$2 AND status='delivering' AND lease_token=$3", message, row['id'], row['lease_token'])

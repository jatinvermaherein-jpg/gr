"""Reminder/note storage: Postgres for production; SQLite for local development."""
import asyncio
import re
import sqlite3
import time
import uuid
from pathlib import Path

SQLITE_DDL = '''
CREATE TABLE IF NOT EXISTS profiles (user_id TEXT PRIMARY KEY, timezone TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS reminders (
 id INTEGER PRIMARY KEY, user_id TEXT NOT NULL, content TEXT NOT NULL,
 due_at INTEGER NOT NULL, zone TEXT NOT NULL, kind TEXT NOT NULL,
 interval_seconds INTEGER, hour INTEGER, minute INTEGER,
 status TEXT NOT NULL DEFAULT 'pending', lease_until INTEGER, lease_token TEXT,
 created_at INTEGER NOT NULL, last_error TEXT
);
CREATE INDEX IF NOT EXISTS reminder_due ON reminders(status,due_at);
CREATE TABLE IF NOT EXISTS notes (id INTEGER PRIMARY KEY, user_id TEXT NOT NULL, content TEXT NOT NULL, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS worker_campaign (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS payout_alerts (user_id TEXT NOT NULL, day TEXT NOT NULL, sent_count INTEGER NOT NULL DEFAULT 0, observed_count INTEGER NOT NULL DEFAULT 0, lease_until INTEGER, lease_token TEXT, last_error TEXT, PRIMARY KEY(user_id,day));
CREATE TABLE IF NOT EXISTS worker_reminders (
 id INTEGER PRIMARY KEY, schedule_key TEXT NOT NULL UNIQUE, user_id TEXT NOT NULL,
 kind TEXT NOT NULL, due_at INTEGER NOT NULL, zone TEXT NOT NULL, hour INTEGER, minute INTEGER,
 status TEXT NOT NULL DEFAULT 'pending', lease_until INTEGER, lease_token TEXT,
 dm_state TEXT NOT NULL DEFAULT 'pending', channel_state TEXT NOT NULL DEFAULT 'pending',
 last_error TEXT, updated_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS worker_reminder_due ON worker_reminders(status,due_at);
'''
PG_DDL = '''
CREATE SCHEMA IF NOT EXISTS mech_bot_app;
REVOKE ALL ON SCHEMA mech_bot_app FROM PUBLIC;
CREATE TABLE IF NOT EXISTS mech_bot_app.profiles (user_id TEXT PRIMARY KEY, timezone TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS mech_bot_app.reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, content TEXT NOT NULL,
 due_at BIGINT NOT NULL, zone TEXT NOT NULL, kind TEXT NOT NULL,
 interval_seconds BIGINT, hour INTEGER, minute INTEGER,
 status TEXT NOT NULL DEFAULT 'pending', lease_until BIGINT, lease_token TEXT,
 created_at BIGINT NOT NULL, last_error TEXT
);
CREATE INDEX IF NOT EXISTS reminder_due ON mech_bot_app.reminders(status,due_at);
CREATE TABLE IF NOT EXISTS mech_bot_app.notes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, content TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS mech_bot_app.worker_campaign (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS mech_bot_app.payout_alerts (user_id TEXT NOT NULL, day TEXT NOT NULL, sent_count INTEGER NOT NULL DEFAULT 0, observed_count INTEGER NOT NULL DEFAULT 0, lease_until BIGINT, lease_token TEXT, last_error TEXT, PRIMARY KEY(user_id,day));
CREATE TABLE IF NOT EXISTS mech_bot_app.worker_reminders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, schedule_key TEXT NOT NULL UNIQUE, user_id TEXT NOT NULL,
 kind TEXT NOT NULL, due_at BIGINT NOT NULL, zone TEXT NOT NULL, hour INTEGER, minute INTEGER,
 status TEXT NOT NULL DEFAULT 'pending', lease_until BIGINT, lease_token TEXT,
 dm_state TEXT NOT NULL DEFAULT 'pending', channel_state TEXT NOT NULL DEFAULT 'pending',
 last_error TEXT, updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS worker_reminder_due ON mech_bot_app.worker_reminders(status,due_at);
'''


class Store:
    def __init__(self, sqlite_path=None, pool=None):
        self.pool = pool
        self.lock = asyncio.Lock()
        self.db = None
        if pool is None:
            path = Path(sqlite_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            self.db = sqlite3.connect(path, isolation_level=None)
            self.db.row_factory = sqlite3.Row
            self.db.executescript(SQLITE_DDL)

    @classmethod
    async def postgres(cls, dsn, auto_migrate=False, ssl_required=True):
        import asyncpg
        # Disable prepared statement caching for Supabase transaction poolers.
        pool = await asyncpg.create_pool(dsn, min_size=1, max_size=4, statement_cache_size=0, ssl='require' if ssl_required else None, command_timeout=20)
        try:
            async with pool.acquire() as conn:
                if auto_migrate:
                    await conn.execute(PG_DDL)
                # Fail fast if the schema has not been deliberately installed.
                for table in ('profiles', 'reminders', 'notes', 'worker_campaign', 'worker_reminders', 'payout_alerts'):
                    await conn.fetchval('SELECT 1 FROM mech_bot_app.'+table+' LIMIT 1')
        except Exception:
            await pool.close()
            raise
        return cls(pool=pool)

    async def close(self):
        if self.pool:
            await self.pool.close()
        if self.db:
            self.db.close()

    def _query(self, sql):
        if self.pool:
            for name in ('worker_campaign','worker_reminders','payout_alerts','profiles','reminders','notes'):
                sql = re.sub(r'(?<![\w.])'+name+r'\b', 'mech_bot_app.'+name, sql)
            return sql
        return re.sub(r'\$\d+', '?', sql)

    async def fetch(self, sql, *args):
        sql = self._query(sql)
        if self.pool:
            async with self.pool.acquire() as conn:
                return [dict(x) for x in await conn.fetch(sql, *args)]
        async with self.lock:
            return [dict(x) for x in self.db.execute(sql, args).fetchall()]

    async def execute(self, sql, *args):
        sql = self._query(sql)
        if self.pool:
            async with self.pool.acquire() as conn:
                return await conn.execute(sql, *args)
        async with self.lock:
            cur = self.db.execute(sql, args)
            return cur.rowcount

    async def set_timezone(self, user_id, zone):
        await self.execute('INSERT INTO profiles(user_id,timezone) VALUES($1,$2) ON CONFLICT(user_id) DO UPDATE SET timezone=excluded.timezone', str(user_id), zone)

    async def get_timezone(self, user_id):
        rows = await self.fetch('SELECT timezone FROM profiles WHERE user_id=$1', str(user_id))
        return rows[0]['timezone'] if rows else 'UTC'

    async def create_reminder(self, user_id, content, spec, zone):
        due, kind, interval, hour, minute = spec
        rows = await self.fetch('INSERT INTO reminders(user_id,content,due_at,zone,kind,interval_seconds,hour,minute,created_at) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9) RETURNING id', str(user_id), content, due, zone, kind, interval, hour, minute, int(time.time()))
        return rows[0]['id']

    async def list_reminders(self, user_id):
        return await self.fetch("SELECT id,content,due_at,zone,kind,status,last_error FROM reminders WHERE user_id=$1 AND status IN ('pending','delivering','failed') ORDER BY due_at LIMIT 25", str(user_id))

    async def cancel_reminder(self, user_id, reminder_id):
        # Owner scope is mandatory. In-flight delivery may already have been sent.
        rows = await self.fetch("UPDATE reminders SET status='cancelled',lease_token=NULL WHERE id=$1 AND user_id=$2 AND status IN ('pending','delivering','failed') RETURNING id", reminder_id, str(user_id))
        return bool(rows)

    async def add_note(self, user_id, content):
        rows = await self.fetch('INSERT INTO notes(user_id,content,created_at) VALUES($1,$2,$3) RETURNING id', str(user_id), content, int(time.time()))
        return rows[0]['id']

    async def list_notes(self, user_id):
        return await self.fetch('SELECT id,content FROM notes WHERE user_id=$1 ORDER BY id DESC LIMIT 25', str(user_id))

    async def delete_note(self, user_id, note_id):
        rows = await self.fetch('DELETE FROM notes WHERE id=$1 AND user_id=$2 RETURNING id', note_id, str(user_id))
        return bool(rows)

    async def claim(self, now, limit=5):
        token = uuid.uuid4().hex
        if self.pool:
            # Atomic multi-worker claim; an expired lease allows recovery after a crash.
            query = '''WITH due AS (
              SELECT id FROM mech_bot_app.reminders
              WHERE (status='pending' AND due_at <= $1) OR (status='delivering' AND lease_until <= $1)
              ORDER BY due_at FOR UPDATE SKIP LOCKED LIMIT $2
            ) UPDATE mech_bot_app.reminders r SET status='delivering', lease_until=$3, lease_token=$4
              FROM due WHERE r.id=due.id RETURNING r.*'''
            async with self.pool.acquire() as conn:
                return [dict(r) for r in await conn.fetch(query, now, limit, now+120, token)]
        async with self.lock:
            self.db.execute('BEGIN IMMEDIATE')
            try:
                ids = [r[0] for r in self.db.execute("SELECT id FROM reminders WHERE (status='pending' AND due_at <= ?) OR (status='delivering' AND lease_until <= ?) ORDER BY due_at LIMIT ?",(now,now,limit))]
                result = []
                for rid in ids:
                    self.db.execute("UPDATE reminders SET status='delivering',lease_until=?,lease_token=? WHERE id=?", (now+120,token,rid))
                    result.append(dict(self.db.execute('SELECT * FROM reminders WHERE id=?',(rid,)).fetchone()))
                self.db.commit()
                return result
            except Exception:
                self.db.rollback()
                raise

    async def complete(self, row, next_due):
        if next_due is None:
            await self.execute("UPDATE reminders SET status='completed',lease_until=NULL,lease_token=NULL,last_error=NULL WHERE id=$1 AND status='delivering' AND lease_token=$2", row['id'], row['lease_token'])
        else:
            await self.execute("UPDATE reminders SET status='pending',due_at=$1,lease_until=NULL,lease_token=NULL,last_error=NULL WHERE id=$2 AND status='delivering' AND lease_token=$3", next_due, row['id'], row['lease_token'])

    async def fail(self, row, message='DM delivery failed; enable DMs, then create a new reminder.'):
        await self.execute("UPDATE reminders SET status='failed',lease_until=NULL,lease_token=NULL,last_error=$1 WHERE id=$2 AND status='delivering' AND lease_token=$3", message, row['id'], row['lease_token'])

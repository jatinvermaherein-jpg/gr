#!/usr/bin/env python3
"""Re-copy the Advisor engine data out of an ARCHANGLE advisor build pack.

The bot never generates these numbers, so they are vendored, hash-pinned and treated as read-only:
rerun this script after the owner ships a newer pack, then commit the diff. `data/advisor/MANIFEST.json`
records the pack name, its build date (the advisor must state a staleness caveat once the data is more
than 30 days old) and the trust tier of every file, because every answer cites those tiers.

    python scripts/import_advisor_pack.py ~/Downloads/archangle-advisor-build-package-20261123.zip \
        --date 2026-11-23
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'data' / 'advisor'

FILES = ['weapon_catalog_tiered.json', 'mech_catalog_tiered.json', 'real_gear_catalogue_299.json',
         'real_upgrade_costs.json', 'ecr_history_261.json', 'weapon_families_251.json', 'pilots_36.json',
         'mods_14.json', 'verified_stat_cells_3520.csv', 'skin_likes.json', 'legendary_skins.json',
         'documents_index_150.json', 'real_store_pricing.csv']

# Community, user-confirmed or unverified: the advisor is allowed to *say* these words, never to
# upgrade a row into a stronger tier than the pack gave it.
TRUST_TIERS = {
    'weapon_catalog_tiered.json': 'community',
    'mech_catalog_tiered.json': 'community',
    'real_gear_catalogue_299.json': 'user-confirmed (store listing)',
    'real_upgrade_costs.json': 'user-confirmed (upgrade ladder)',
    'ecr_history_261.json': 'community',
    'weapon_families_251.json': 'user-confirmed (item identity)',
    'pilots_36.json': 'community',
    'mods_14.json': 'community',
    'verified_stat_cells_3520.csv': 'user-confirmed',
    'skin_likes.json': 'community',
    'legendary_skins.json': 'community',
    'documents_index_150.json': 'unverified',
    'real_store_pricing.csv': 'user-confirmed',
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('pack', help='path to an archangle-advisor-build-package-*.zip')
    parser.add_argument('--dest', default=str(DEST), help='where to write the files (default: data/advisor)')
    parser.add_argument('--date', default='', help='pack build date, recorded for the staleness caveat')
    args = parser.parse_args()

    dest = Path(args.dest)
    dest.mkdir(parents=True, exist_ok=True)
    copied, missing = {}, []
    with zipfile.ZipFile(args.pack) as archive:
        lookup = {os.path.basename(info.filename): info for info in archive.infolist()}
        for name in FILES:
            info = lookup.get(name)
            if info is None:
                missing.append(name)
                continue
            payload = archive.read(info)
            (dest / name).write_bytes(payload)
            copied[name] = {'bytes': len(payload), 'sha256': hashlib.sha256(payload).hexdigest()}

    manifest = {
        'source': os.path.basename(args.pack),
        'pack_build_date': args.date,
        'note': ('Advisor engine data, copied verbatim from the build pack and hash-pinned. Nothing here is '
                 'generated by the bot. Regenerated by scripts/import_advisor_pack.py.'),
        'trust_tiers': {name: TRUST_TIERS[name] for name in FILES},
        'files': copied,
    }
    (dest / 'MANIFEST.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + '\n')

    print(f'wrote {len(copied)} of {len(FILES)} files into {dest}')
    for name in FILES:
        record = copied.get(name)
        if record:
            print(f'  {name:34s} {record["bytes"]:>8,} bytes  {record["sha256"][:16]}')
    if missing:
        print('missing from the pack: ' + ', '.join(missing))
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

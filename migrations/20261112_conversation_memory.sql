-- Short-lived, private per-user/per-channel conversation context; existing data is untouched.
BEGIN;
CREATE TABLE IF NOT EXISTS mech_bot_app.conversation_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    guild_id TEXT NOT NULL,
    channel_id TEXT NOT NULL,
    user_content TEXT NOT NULL,
    assistant_content TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS conversation_scope
    ON mech_bot_app.conversation_turns (user_id, guild_id, channel_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS conversation_expiry
    ON mech_bot_app.conversation_turns (expires_at);
REVOKE ALL ON TABLE mech_bot_app.conversation_turns FROM PUBLIC;
GRANT SELECT, INSERT, DELETE
    ON TABLE mech_bot_app.conversation_turns TO mech_bot_runtime;
GRANT USAGE, SELECT
    ON SEQUENCE mech_bot_app.conversation_turns_id_seq TO mech_bot_runtime;
COMMIT;
